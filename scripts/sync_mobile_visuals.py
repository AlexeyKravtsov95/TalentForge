#!/usr/bin/env python3
"""Synchronize the canonical talent visuals into the mobile runtime bundle.

The canonical source of truth is ``data/visuals/forever/<build>/`` (nine
``talent-visuals.v1`` sidecars, the ``talent-icons.v1`` registry ``icons.json``
and ``icons/<FileDataID>.png``). The mobile application packages a copy, for every
bundled build (``BUNDLED_BUILDS`` in ``scripts/mobile_bundles.py``), as Compose
Multiplatform resources; that copy must be byte-identical to the canonical files and
contain nothing else, otherwise the app would ship stale, hand-edited or orphaned icon
assets. Each build keeps its own icons; nothing is shared or substituted across builds.

Nothing here touches the network or the DB2/CASC cache: icons are generated by
``python -m talent_data visuals fetch|normalize`` (online, on demand) and this
script only mirrors what is already committed.

Modes:
    (default)  mirror the canonical directories of the bundled builds into the bundle
               (copies changed files, removes files that are no longer canonical, never
               removes the bundle of another build)
    --check    fail (exit 1) if the bundle differs from the canonical data; offline, used
               by CI to catch visual drift

Usage:
    python scripts/sync_mobile_visuals.py
    python scripts/sync_mobile_visuals.py --check
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from mobile_bundles import VISUALS, run


def main(argv: list[str] | None = None) -> int:
    return run(VISUALS, argv, doc=__doc__)


if __name__ == "__main__":
    raise SystemExit(main())
