#!/usr/bin/env python3
"""Mirror the OTA contract v1 fixtures into the mobile test sources (M5.OTA.3).

The conformance suite ``docs/ota/fixtures/v1/`` (``cases.json``, the keyring, signed
catalogs, release manifests and blobs) is owned by the contract (M5.OTA.1) and regenerated
only by ``scripts/generate_ota_fixtures.py``. The Kotlin client replays it:

* ``mobile/shared/src/jvmTest/resources/ota/fixtures/v1/`` - a byte-identical mirror of the
  whole directory, read by the JVM replay of all 64 cases (``OtaConformanceReplayTest``);
* ``mobile/composeApp/src/iosTest/kotlin/.../ota/OtaCatalogFixtureVectors.kt`` - the pinned
  keys and the catalog cases as Kotlin constants, so the iOS simulator test can replay the
  catalog verification (signatures through Security.framework) without reading host files.
  The 1 MiB + 1 byte ``catalog-over-size-limit`` envelope is the one catalog left out: it is
  rejected by its size before any signature is looked at, and the size check is common
  code replayed on the JVM.

Both are derived copies and never hand-edited. Standard library only and offline.

Usage:
    python3 scripts/sync_mobile_ota_fixtures.py           # rewrite the mirror and the vectors
    python3 scripts/sync_mobile_ota_fixtures.py --check   # exit 1 when either drifted
"""

from __future__ import annotations

import argparse
import base64
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SOURCE = REPO_ROOT / "docs" / "ota" / "fixtures" / "v1"
MIRROR = REPO_ROOT / "mobile" / "shared" / "src" / "jvmTest" / "resources" / "ota" / "fixtures" / "v1"
VECTORS = (
    REPO_ROOT
    / "mobile"
    / "composeApp"
    / "src"
    / "iosTest"
    / "kotlin"
    / "io"
    / "github"
    / "alexeykravtsov95"
    / "talentforge"
    / "ui"
    / "ota"
    / "OtaCatalogFixtureVectors.kt"
)
EXPECTED_CASES = 64
IOS_SKIPPED = ("catalog-over-size-limit",)


def relative_files(directory: Path) -> set[str]:
    if not directory.is_dir():
        return set()
    # Dotfiles (Finder's .DS_Store, editor droppings) are OS noise, never fixture content.
    return {
        p.relative_to(directory).as_posix()
        for p in directory.rglob("*")
        if p.is_file() and not any(part.startswith(".") for part in p.relative_to(directory).parts)
    }


def mirror_drift() -> list[str]:
    source = relative_files(SOURCE)
    mirror = relative_files(MIRROR)
    problems = [f"{name}: missing from the mirror" for name in sorted(source - mirror)]
    problems += [f"{name}: in the mirror but not a fixture" for name in sorted(mirror - source)]
    problems += [
        f"{name}: mirror differs from the fixture"
        for name in sorted(source & mirror)
        if (SOURCE / name).read_bytes() != (MIRROR / name).read_bytes()
    ]
    return problems


def _kotlin_string(value: str | None) -> str:
    if value is None:
        return "null"
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    return f'"{escaped}"'


def _kotlin_long(value: int | None) -> str:
    return "null" if value is None else f"{value}L"


def render_vectors() -> str:
    cases = json.loads((SOURCE / "cases.json").read_text(encoding="utf-8"))
    if len(cases["cases"]) != EXPECTED_CASES:
        raise ValueError(f"cases.json has {len(cases['cases'])} cases, expected {EXPECTED_CASES}")
    keyring = json.loads((SOURCE / "keyring.json").read_text(encoding="utf-8"))
    lines = [
        "// GENERATED by scripts/sync_mobile_ota_fixtures.py from docs/ota/fixtures/v1 - do not edit.",
        "// Check: python3 scripts/sync_mobile_ota_fixtures.py --check",
        "package io.github.alexeykravtsov95.talentforge.ui.ota",
        "",
        "internal object OtaCatalogFixtureVectors {",
        "    class Key(val keyId: String, val algorithm: String, val publicKeySpki: String)",
        "",
        "    class Case(",
        "        val id: String,",
        "        val envelopeBase64: String,",
        "        val game: String,",
        "        val channel: String,",
        "        val now: String,",
        "        val lastSeenSequence: Long?,",
        "        val lastSeenPayloadSha256: String?,",
        "        val supportedDataLevel: Int,",
        "        val bundledProductBuild: String,",
        "        val currentReleaseId: String?,",
        "        val expectResult: String,",
        "        val expectCode: String?,",
        "        val expectDecision: String?,",
        "        val expectReleaseId: String?,",
        "    )",
        "",
        "    /** The pinned TEST keys (keyring.json `keys`); `untrustedKeys` are never pinned. */",
        "    val keys: List<Key> = listOf(",
    ]
    for key in keyring["keys"]:
        lines.append(
            f"        Key({_kotlin_string(key['keyId'])}, {_kotlin_string(key['algorithm'])}, "
            f"{_kotlin_string(key['publicKeySpki'])}),"
        )
    lines += ["    )", "", f"    val skipped: List<String> = listOf({', '.join(_kotlin_string(s) for s in IOS_SKIPPED)})", ""]
    lines.append("    val cases: List<Case> = listOf(")
    for case in cases["cases"]:
        if case["kind"] != "catalog" or case["id"] in IOS_SKIPPED:
            continue
        ctx = case["context"]
        seen = ctx["lastSeen"]
        expect = case["expect"]
        envelope = base64.b64encode((SOURCE / case["file"]).read_bytes()).decode("ascii")
        lines += [
            "        Case(",
            f"            id = {_kotlin_string(case['id'])},",
            f"            envelopeBase64 = {_kotlin_string(envelope)},",
            f"            game = {_kotlin_string(ctx['game'])},",
            f"            channel = {_kotlin_string(ctx['channel'])},",
            f"            now = {_kotlin_string(ctx['now'])},",
            f"            lastSeenSequence = {_kotlin_long(seen['sequence'] if seen else None)},",
            f"            lastSeenPayloadSha256 = {_kotlin_string(seen['payloadSha256'] if seen else None)},",
            f"            supportedDataLevel = {ctx['supportedDataLevel']},",
            f"            bundledProductBuild = {_kotlin_string(ctx['bundledProductBuild'])},",
            f"            currentReleaseId = {_kotlin_string(ctx['currentReleaseId'])},",
            f"            expectResult = {_kotlin_string(expect['result'])},",
            f"            expectCode = {_kotlin_string(expect.get('code'))},",
            f"            expectDecision = {_kotlin_string(expect.get('decision'))},",
            f"            expectReleaseId = {_kotlin_string(expect.get('releaseId'))},",
            "        ),",
        ]
    lines += ["    )", "}", ""]
    return "\n".join(lines)


def check() -> int:
    problems = mirror_drift()
    expected = render_vectors()
    if not VECTORS.is_file():
        problems.append(f"{VECTORS.relative_to(REPO_ROOT)}: missing")
    elif VECTORS.read_text(encoding="utf-8") != expected:
        problems.append(f"{VECTORS.relative_to(REPO_ROOT)}: differs from the fixtures")
    if problems:
        print("mobile OTA fixtures are out of sync with docs/ota/fixtures/v1:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        print("run: python3 scripts/sync_mobile_ota_fixtures.py", file=sys.stderr)
        return 1
    print(
        f"OTA fixtures in sync: {len(relative_files(SOURCE))} files mirrored, "
        f"{EXPECTED_CASES} cases, iOS catalog vectors current"
    )
    return 0


def sync() -> int:
    vectors = render_vectors()  # validates cases.json before anything is written
    source = relative_files(SOURCE)
    copied = removed = 0
    for name in sorted(source):
        data = (SOURCE / name).read_bytes()
        target = MIRROR / name
        if target.is_file() and target.read_bytes() == data:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        copied += 1
    for name in sorted(relative_files(MIRROR) - source):
        (MIRROR / name).unlink()
        removed += 1
    VECTORS.parent.mkdir(parents=True, exist_ok=True)
    if not VECTORS.is_file() or VECTORS.read_text(encoding="utf-8") != vectors:
        VECTORS.write_text(vectors, encoding="utf-8")
    print(f"synced {len(source)} OTA fixture files ({copied} copied, {removed} removed) and the iOS vectors")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="verify the mirror and the vectors instead of writing")
    args = parser.parse_args(argv)
    return check() if args.check else sync()


if __name__ == "__main__":
    raise SystemExit(main())
