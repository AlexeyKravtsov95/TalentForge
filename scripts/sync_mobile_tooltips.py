#!/usr/bin/env python3
"""Synchronize the canonical talent tooltips into the mobile runtime bundle.

The canonical source of truth is ``data/tooltips/forever/<build>/`` (nine
``talent-tooltips.v1`` sidecars). The mobile application packages a copy as
Compose Multiplatform resources; that copy must be byte-identical to the
canonical files and contain nothing else, otherwise the app would ship stale or
hand-edited descriptions.

Nothing here touches the network or the DB2 cache: descriptions are generated by
``python -m talent_data tooltips fetch|normalize`` (on demand) and this script
only mirrors what is already committed.

Modes:
    (default)  mirror the canonical directory into the bundled resource directory
               (copies changed files, removes files that are no longer canonical)
    --check    fail (exit 1) if the bundle differs from the canonical directory;
               used by CI to catch description drift

Usage:
    python scripts/sync_mobile_tooltips.py
    python scripts/sync_mobile_tooltips.py --check
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

GAME = "forever"
BASELINE_BUILD = "1.60.1.70009"
# Every class sidecar must exist before anything is mirrored.
CLASS_FILES = (
    "warrior.json",
    "paladin.json",
    "hunter.json",
    "rogue.json",
    "priest.json",
    "shaman.json",
    "mage.json",
    "warlock.json",
    "druid.json",
)

REPO_ROOT = Path(__file__).resolve().parent.parent
CANONICAL_DIR = REPO_ROOT / "data" / "tooltips" / GAME / BASELINE_BUILD
BUNDLED_DIR = (
    REPO_ROOT
    / "mobile"
    / "composeApp"
    / "src"
    / "commonMain"
    / "composeResources"
    / "files"
    / "tooltips"
    / GAME
    / BASELINE_BUILD
)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the bundle matches the canonical tooltips instead of copying",
    )
    return parser.parse_args(argv)


def relative_files(directory: Path) -> set[str]:
    if not directory.is_dir():
        return set()
    # Dotfiles (Finder's .DS_Store, editor droppings) are OS noise, never tooltips.
    return {
        p.relative_to(directory).as_posix()
        for p in directory.rglob("*")
        if p.is_file() and not p.name.startswith(".")
    }


def drift(canonical_dir: Path, bundled_dir: Path) -> list[str]:
    """Every way the bundle differs from the canonical directory (empty = in sync)."""
    canonical = relative_files(canonical_dir)
    bundled = relative_files(bundled_dir)
    problems = [f"{name}: missing from bundle" for name in sorted(canonical - bundled)]
    problems += [f"{name}: in bundle but not canonical" for name in sorted(bundled - canonical)]
    problems += [
        f"{name}: bundle differs from canonical"
        for name in sorted(canonical & bundled)
        if (canonical_dir / name).read_bytes() != (bundled_dir / name).read_bytes()
    ]
    return problems


def check(canonical_dir: Path = CANONICAL_DIR, bundled_dir: Path = BUNDLED_DIR) -> int:
    problems = drift(canonical_dir, bundled_dir)
    if problems:
        print("mobile tooltips bundle is out of sync with canonical data:", file=sys.stderr)
        for problem in problems:
            print(f"  - {problem}", file=sys.stderr)
        print("run: python scripts/sync_mobile_tooltips.py", file=sys.stderr)
        return 1
    print(f"bundle in sync: {len(relative_files(canonical_dir))} files match {canonical_dir}")
    return 0


def sync(canonical_dir: Path = CANONICAL_DIR, bundled_dir: Path = BUNDLED_DIR) -> int:
    canonical = relative_files(canonical_dir)
    copied = 0
    for name in sorted(canonical):
        source = canonical_dir / name
        target = bundled_dir / name
        data = source.read_bytes()
        if target.is_file() and target.read_bytes() == data:
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        copied += 1
    stale = sorted(relative_files(bundled_dir) - canonical)
    for name in stale:
        (bundled_dir / name).unlink()
    print(
        f"synced {len(canonical)} files into {bundled_dir} ({copied} copied, {len(stale)} removed)"
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    missing = [name for name in CLASS_FILES if not (CANONICAL_DIR / name).is_file()]
    if missing:
        print(f"canonical tooltips are missing in {CANONICAL_DIR}: {missing}", file=sys.stderr)
        return 1
    return check() if args.check else sync()


if __name__ == "__main__":
    raise SystemExit(main())
