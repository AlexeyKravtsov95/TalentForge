#!/usr/bin/env python3
"""Synchronize the canonical ruRU talent text overlays into the mobile runtime bundle.

The canonical source of truth is ``data/localization/forever/<build>/ruRU/`` (nine
``talent-localization.v1`` overlays per build, one per class). The mobile application
packages a copy, for every bundled build (``BUNDLED_BUILDS`` in
``scripts/mobile_bundles.py``), as Compose Multiplatform resources; that copy must be
byte-identical to the canonical files and contain nothing else, otherwise the app would
ship stale or hand-edited localized text. The overlays are presentation-only: the dataset,
tooltip, visual and allocation bundles are not touched by this script.

Nothing here touches the network or the DB2 cache: overlays are generated by
``python -m talent_data localization fetch|normalize`` (on demand) and this script
only mirrors what is already committed.

Modes:
    (default)  mirror the canonical directories of the bundled builds into the bundle
               (copies changed files, removes files that are no longer canonical, never
               removes the bundle of another build)
    --check    fail (exit 1) if the bundle differs from the canonical data; offline, used
               by CI to catch localization drift

Usage:
    python scripts/sync_mobile_localization.py
    python scripts/sync_mobile_localization.py --check
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from mobile_bundles import LOCALIZATION, run


def main(argv: list[str] | None = None) -> int:
    return run(LOCALIZATION, argv, doc=__doc__)


if __name__ == "__main__":
    raise SystemExit(main())
