package io.github.alexeykravtsov95.talentforge.ui.ota

import io.github.alexeykravtsov95.talentforge.data.ota.InvalidKeyringException
import io.github.alexeykravtsov95.talentforge.data.ota.OtaChannel
import io.github.alexeykravtsov95.talentforge.data.ota.OtaContract
import io.github.alexeykravtsov95.talentforge.data.ota.OtaKeyring

/** One pinned key as Gradle generates it (contract §8 keyring entry). */
data class OtaKeySetting(val keyId: String, val algorithm: String, val publicKeySpki: String)

/**
 * The compile-time OTA settings of one platform and build type (client design §8),
 * generated by `:composeApp:generateOtaSettings` from Gradle properties into
 * [GeneratedOtaSettings]. Android and iOS are configured independently (OD-17). Every
 * default is "off": no base URL, no keys, `enabled = false` — the owner supplies hosting and
 * public keys (OD-1, OD-2) before any build can turn it on.
 */
data class OtaPlatformSettings(
    val enabled: Boolean,
    val channel: OtaChannel,
    val baseUrl: String?,
    val keys: List<OtaKeySetting>,
)

/**
 * A validated, enabled OTA configuration. Never read from a downloaded document: the base
 * URL and the keyring are compiled into the app (contract §1, §8), so no document can
 * redirect the client or add a key.
 */
class OtaConfig private constructor(
    val game: String,
    val channel: OtaChannel,
    val baseUrl: String,
    val keyring: OtaKeyring,
    val supportedDataLevel: Int,
    /** Concurrent blob downloads (client design §4.3; measured in test-plan §7). */
    val parallelism: Int,
) {
    /** `GET <base>/v1/channels/<channel>/catalog.json` (contract §1). */
    val catalogUrl: String get() = "$baseUrl/v1/channels/${channel.wire}/catalog.json"

    /** `GET <base>/v1/blobs/sha256/<hex>` (contract §1). */
    fun blobUrl(sha256Hex: String): String = "$baseUrl/v1/blobs/sha256/$sha256Hex"

    /** Why a platform's settings do not yield an enabled client; every case runs the app on bundled data only. */
    enum class DisabledReason {
        NOT_ENABLED,
        BAD_BASE_URL,
        NO_KEYS,
        BAD_KEYRING,
        TEST_KEY_IN_APP_KEYRING,
        PRODUCTION_NEEDS_BACKUP_KEY,
    }

    sealed interface Resolution {
        data class Enabled(val config: OtaConfig) : Resolution

        data class Disabled(val reason: DisabledReason) : Resolution
    }

    companion object {
        const val GAME: String = "forever"
        const val DEFAULT_PARALLELISM: Int = 4

        /** `https://host[:port][/path]` without query, fragment, credentials or a trailing slash. */
        private val BASE_URL = Regex("https://[A-Za-z0-9.-]+(:[0-9]{1,5})?(/[A-Za-z0-9._~-]+)*")

        /**
         * Resolves app settings fail-closed: anything short of a complete, valid configuration
         * is [Resolution.Disabled]. An app keyring never contains a `test-` key (contract §8),
         * and a production keyring pins a primary and a backup key.
         */
        fun resolve(settings: OtaPlatformSettings): Resolution {
            if (!settings.enabled) return Resolution.Disabled(DisabledReason.NOT_ENABLED)
            val baseUrl = settings.baseUrl
            if (baseUrl == null || !BASE_URL.matches(baseUrl)) return Resolution.Disabled(DisabledReason.BAD_BASE_URL)
            if (settings.keys.isEmpty()) return Resolution.Disabled(DisabledReason.NO_KEYS)
            val keyring = try {
                OtaKeyring.of(settings.keys.map { OtaKeyring.Entry(it.keyId, it.algorithm, it.publicKeySpki) })
            } catch (_: InvalidKeyringException) {
                return Resolution.Disabled(DisabledReason.BAD_KEYRING)
            }
            if (keyring.containsTestKey) return Resolution.Disabled(DisabledReason.TEST_KEY_IN_APP_KEYRING)
            if (settings.channel == OtaChannel.PRODUCTION && keyring.keyIds.size < 2) {
                return Resolution.Disabled(DisabledReason.PRODUCTION_NEEDS_BACKUP_KEY)
            }
            return Resolution.Enabled(
                OtaConfig(GAME, settings.channel, baseUrl, keyring, OtaContract.SUPPORTED_DATA_LEVEL, DEFAULT_PARALLELISM),
            )
        }

        /**
         * An injected configuration for tests and benchmarks (client design §8: "Desktop / JVM
         * tests: injected, fake BlobFetcher, fixture keyring"). The only way a `test-` key can be
         * pinned; no app entry point calls it.
         */
        fun forTesting(
            keyring: OtaKeyring,
            baseUrl: String = "https://ota.invalid",
            channel: OtaChannel = OtaChannel.PRODUCTION,
            supportedDataLevel: Int = OtaContract.SUPPORTED_DATA_LEVEL,
            parallelism: Int = DEFAULT_PARALLELISM,
        ): OtaConfig = OtaConfig(GAME, channel, baseUrl, keyring, supportedDataLevel, parallelism)
    }
}
