package io.github.alexeykravtsov95.talentforge.ui.about

import io.github.alexeykravtsov95.talentforge.composeapp.generated.resources.Res
import kotlinx.coroutines.CancellationException
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonNull
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive

/**
 * The open-source notices of one platform's distributed binary (LR-4): every
 * third-party component it ships, each with its licences, and the full text of
 * every licence bundled next to it.
 *
 * The file is GENERATED by `scripts/generate_oss_notices.py` — from the
 * resolved release runtime classpath (Android) or the klibs linked into the
 * iOS framework, licences read from each module's POM, native code from the
 * klibs' static archives — and drift-checked in CI; never edited by hand.
 */
data class OpenSourceNotices(
    val platform: String,
    val licenses: Map<String, NoticeLicense>,
    val components: List<NoticeComponent>,
) {
    /** The Gradle modules listed (linked native components are not modules). */
    val moduleCount: Int get() = components.sumOf { (it as? NoticeComponent.Packaged)?.modules?.size ?: 0 }

    /**
     * The groups the Licenses screen shows (M5.UI.ABOUT.2): one per packaged
     * component, in document order, with every linked component placed in the
     * group of the packaged component whose module contains it (Skia and the
     * other native code in Skiko's group). Derived from the data alone — no
     * curated mapping — so every component lands in exactly one group: the
     * parser guarantees each linked component's module is listed, and once.
     */
    val groups: List<NoticeGroup>
        get() {
            val linked = components.filterIsInstance<NoticeComponent.Linked>()
            return components.filterIsInstance<NoticeComponent.Packaged>().map { head ->
                NoticeGroup(head = head, linked = linked.filter { it.linkedInto in head.modules })
            }
        }

    /** The components whose licence requires a statement in the product documentation, in document order. */
    val attributions: List<NoticeComponent.Linked>
        get() = components.filterIsInstance<NoticeComponent.Linked>().filter { it.attribution != null }

    /** Every component distributed under [licenseId], in document order. */
    fun componentsUnder(licenseId: String): List<NoticeComponent> = components.filter { licenseId in it.licenseIds }
}

/** One group of the Licenses screen: a packaged component and the third-party code linked into it. */
data class NoticeGroup(
    val head: NoticeComponent.Packaged,
    val linked: List<NoticeComponent.Linked>,
) {
    val components: List<NoticeComponent> get() = listOf(head) + linked

    /** Every licence of the group's components, each once, in first-use order. */
    val licenseIds: List<String> get() = components.flatMap { it.licenseIds }.distinct()
}

/** A licence or notice text the notices reference: display name and the bundled full text's resource path. */
data class NoticeLicense(val id: String, val name: String, val textPath: String)

/** A shipped component, under every licence in [licenseIds] (each declared in the document). */
sealed interface NoticeComponent {
    val name: String
    val url: String
    val licenseIds: List<String>

    /** Gradle modules the binary ships. */
    data class Packaged(
        override val name: String,
        override val url: String,
        override val licenseIds: List<String>,
        /** `group:artifact:version` coordinates, as Gradle resolved them. */
        val modules: List<String>,
    ) : NoticeComponent

    /** Third-party code statically linked into one of the listed modules (e.g. Skia into Skiko). */
    data class Linked(
        override val name: String,
        override val url: String,
        override val licenseIds: List<String>,
        val version: String,
        /** The listed module whose binary contains it. */
        val linkedInto: String,
        /** A statement its licence requires in the product documentation, verbatim; `null` when none. */
        val attribution: String?,
    ) : NoticeComponent
}

/** The notices file or a licence text is missing, unreadable or malformed. */
class OpenSourceNoticesException(message: String, cause: Throwable? = null) : Exception(message, cause)

const val OSS_NOTICES_SCHEMA = "talentforge.oss-notices.v2"

private val PACKAGED_KEYS = setOf("name", "url", "licenses", "modules")
private val LINKED_KEYS = setOf("name", "url", "licenses", "version", "linkedInto", "attribution")

/**
 * Strict parse: the exact v2 shape, no unknown or missing keys, no wrong wire
 * types, no empty or duplicate lists, every component's licences declared and
 * every declared licence used, every licence text path under `files/legal/`,
 * every module listed once, every linked component inside a listed module.
 * Anything else throws — a half-read notice list must never be shown as complete.
 */
fun parseOpenSourceNotices(text: String): OpenSourceNotices {
    val root = try {
        Json.parseToJsonElement(text)
    } catch (e: IllegalArgumentException) {
        throw OpenSourceNoticesException("notices are not valid JSON", e)
    }.asObject("notices", setOf("schema", "platform", "source", "licenses", "components"))
    val schema = root.string("schema")
    if (schema != OSS_NOTICES_SCHEMA) throw OpenSourceNoticesException("unsupported notices schema '$schema'")
    root.string("source")

    val licenses = root.getValue("licenses").asObject("licenses", keys = null).mapValues { (id, value) ->
        val license = value.asObject("license $id", setOf("name", "file"))
        val path = license.string("file")
        if (!path.startsWith("files/legal/")) throw OpenSourceNoticesException("licence $id text outside files/legal/")
        NoticeLicense(id = id, name = license.string("name"), textPath = path)
    }
    if (licenses.isEmpty()) throw OpenSourceNoticesException("no licences declared")

    val components = root.getValue("components").asArray("components").mapIndexed { index, value ->
        val what = "component $index"
        val component = value as? JsonObject ?: throw OpenSourceNoticesException("$what is not an object")
        if (component.keys != PACKAGED_KEYS && component.keys != LINKED_KEYS) {
            throw OpenSourceNoticesException(
                "$what has keys ${component.keys.sorted()}, expected ${PACKAGED_KEYS.sorted()} or ${LINKED_KEYS.sorted()}",
            )
        }
        val licenseIds = component.strings("licenses", what)
        for (id in licenseIds) {
            if (id !in licenses) throw OpenSourceNoticesException("$what: undeclared licence '$id'")
        }
        if (component.keys == PACKAGED_KEYS) {
            NoticeComponent.Packaged(
                name = component.string("name"),
                url = component.string("url"),
                licenseIds = licenseIds,
                modules = component.strings("modules", what).onEach { coordinate ->
                    if (coordinate.split(':').let { parts -> parts.size != 3 || parts.any(String::isEmpty) }) {
                        throw OpenSourceNoticesException("$what: '$coordinate' is not group:artifact:version")
                    }
                },
            )
        } else {
            NoticeComponent.Linked(
                name = component.string("name"),
                url = component.string("url"),
                licenseIds = licenseIds,
                version = component.string("version"),
                linkedInto = component.string("linkedInto"),
                attribution = if (component.getValue("attribution") is JsonNull) null else component.string("attribution"),
            )
        }
    }
    if (components.isEmpty()) throw OpenSourceNoticesException("no components listed")
    val modules = components.filterIsInstance<NoticeComponent.Packaged>().flatMap { it.modules }
    if (modules.size != modules.toSet().size) throw OpenSourceNoticesException("a module is listed twice")
    for (linked in components.filterIsInstance<NoticeComponent.Linked>()) {
        if (linked.linkedInto !in modules) {
            throw OpenSourceNoticesException("'${linked.name}' is linked into '${linked.linkedInto}', which is not listed")
        }
    }
    val unused = licenses.keys - components.flatMap { it.licenseIds }.toSet()
    if (unused.isNotEmpty()) throw OpenSourceNoticesException("licences declared but not used: ${unused.sorted()}")
    return OpenSourceNotices(platform = root.string("platform"), licenses = licenses, components = components)
}

private fun JsonElement.asObject(what: String, keys: Set<String>?): JsonObject {
    val value = this as? JsonObject ?: throw OpenSourceNoticesException("$what is not an object")
    if (keys != null && value.keys != keys) {
        throw OpenSourceNoticesException("$what has keys ${value.keys.sorted()}, expected ${keys.sorted()}")
    }
    return value
}

private fun JsonElement.asArray(what: String): JsonArray =
    this as? JsonArray ?: throw OpenSourceNoticesException("$what is not an array")

/** A non-empty array of distinct non-empty strings. */
private fun JsonObject.strings(key: String, what: String): List<String> {
    val values = getValue(key).asArray("$what $key").map { element ->
        (element as? JsonPrimitive)?.takeIf { it.isString }?.content?.takeIf { it.isNotBlank() }
            ?: throw OpenSourceNoticesException("$what: a $key entry is not a non-empty string")
    }
    if (values.isEmpty()) throw OpenSourceNoticesException("$what has no $key")
    if (values.size != values.toSet().size) throw OpenSourceNoticesException("$what lists a $key entry twice")
    return values
}

private fun JsonObject.string(key: String): String =
    (getValue(key) as? JsonPrimitive)?.takeIf { it.isString }?.content?.takeIf { it.isNotBlank() }
        ?: throw OpenSourceNoticesException("'$key' is not a non-empty string")

/** Reads a bundled legal resource (`files/legal/…`) as UTF-8 text, as a typed failure. */
suspend fun readLegalResource(path: String): String = try {
    Res.readBytes(path).decodeToString()
} catch (e: CancellationException) {
    throw e
} catch (e: Exception) {
    throw OpenSourceNoticesException("cannot read $path", e)
}

/** Loads and strictly parses the notices at [path]. */
suspend fun loadOpenSourceNotices(path: String): OpenSourceNotices = parseOpenSourceNotices(readLegalResource(path))
