BASE = ClientVersion.parse("1.60.1.70938")
TARGET = ClientVersion.parse("1.60.1.70959")


def page(number: int = 1, *, changed: tuple[int, ...] = (1, 2), **edits: object) -> bytes:
    rows = [{"Action": "modified", "FDID": i, "Filename": None, "Type": None} for i in changed]
    props = {
        "fromVersion": str(BASE),
        "toVersion": str(TARGET),
        "branch": None,
        "filters": {"from": str(BASE), "to": str(TARGET), "page": str(number)},
        "counts": {"added": 0, "removed": 0, "changed": len(rows)},
        "items": {
            "current_page": number,
            "last_page": max(1, len(rows)),
            "per_page": 1,
            "total": len(rows),
            "data": rows[number - 1 : number],
        },
        **edits,
    }
    raw = json.dumps({"component": "Builds/Diff", "props": props})
    return f'<div data-page="{html.escape(raw, quote=True)}"></div>'.encode()


@pytest.mark.parametrize(
    "edits",
    [
        {"errors": {"to": "root unavailable"}},
        {"toVersion": str(BASE)},
        {"fromVersion": str(TARGET)},
        {"filters": {"search": "blp"}},
        {"branch": "wowf"},
        {"counts": {"added": 0, "removed": 0, "changed": "2"}},
        {"items": {"current_page": 1, "last_page": 1, "total": 2, "per_page": 1, "data": []}},
    ],
)
def test_partial_filtered_or_wrong_build_diff_never_proves_equality(edits: dict) -> None:
    with pytest.raises(SourceError, match="CASC_DIFF_INVALID"):
        parse_page(page(**edits), str(BASE), str(TARGET), 1)


def test_completed_pages_resume_after_network_failure(tmp_path: Path) -> None:
    requests = []
    fail = True

    def handler(request: httpx.Request) -> httpx.Response:
        nonlocal fail
        n = int(request.url.params["page"])
        requests.append(n)
        if n == 2 and fail:
            raise httpx.ReadError("TLS EOF", request=request)
        return httpx.Response(200, content=page(n))

    with HttpClient(HttpConfig(max_attempts=1), transport=httpx.MockTransport(handler)) as http:
        with pytest.raises(DownloadError):
            load_diff(http, tmp_path, BASE, TARGET)
        fail = False
        result = load_diff(http, tmp_path, BASE, TARGET)
        assert result.changed == {1, 2}
        assert requests == [1, 2, 2]  # verified page 1 is not downloaded again
        assert load_diff(None, tmp_path, BASE, TARGET) == result
    result.pages[0].write_bytes(b"tampered")
    with pytest.raises(SourceError, match="MISSING"):
        load_diff(None, tmp_path, BASE, TARGET)


def test_duplicate_ids_across_pages_are_not_a_complete_diff(tmp_path: Path) -> None:
    with (
        HttpClient(
            transport=httpx.MockTransport(
                lambda r: httpx.Response(
                    200, content=page(int(r.url.params["page"]), changed=(1, 1))
                )
            )
        ) as http,
        pytest.raises(SourceError, match="duplicate FileDataID"),
    ):
        load_diff(http, tmp_path, BASE, TARGET)


def test_reuse_requires_verified_png_and_excludes_new_or_modified_ids(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    monkeypatch.setenv("TALENT_DATA_ROOT", str(ROOT))
    monkeypatch.setenv("TALENT_DATA_CACHE_ROOT", str(tmp_path / "cache"))
    # Keep the evidence generated by this test outside the repository.
    monkeypatch.setattr(
        "talent_data.visuals.reuse.paths.icon_coverage_path",
        lambda *args: tmp_path / "coverage.json",
    )
    registry = json.loads((ROOT / f"data/visuals/forever/{BASE}/icons.json").read_bytes())
    same_id, modified_id = [a["fileDataId"] for a in registry["icons"][:2]]
    new_id = 99999999
    requested = []

    def handler(request: httpx.Request) -> httpx.Response:
        requested.append(str(request.url))
        return httpx.Response(200, content=page(changed=(modified_id,)))

    with HttpClient(transport=httpx.MockTransport(handler)) as http:
        plan = plan_reuse("forever", BASE, TARGET, [same_id, modified_id, new_id], http)
    assert set(plan.icons) == {same_id}
    old = registry["icons"][0]
    assert plan.icons[same_id].source_sha256 == old["sourceSha256"]
    assert (
        plan.icons[same_id].png
        == (ROOT / f"data/visuals/forever/{BASE}" / old["file"]).read_bytes()
    )
    assert len(requested) == 1 and "/builds-diff?" in requested[0]
    evidence = json.loads((tmp_path / f"forever-{TARGET}-icon-reuse.json").read_bytes())
    assert evidence["fetchRequired"] == sorted([modified_id, new_id])
    assert evidence["reused"][0]["sha256"] == old["sha256"]
